cat <<'BANNER'
==================================================================
OPENMW 0.51 — VISGRID V22.1D INTERCELL PVS QUARANTINE + DEEP DEBUG
==================================================================
This deliberately REBASES on exact V22.1, not V22.2.

What changes from V22.1:
  1. Interior cell ownership boundary:
     - clear BOTH engine VISGRID and topology-PVS stores on intercell change
     - purge cell-local PVS recent IDs, portal latches, resident IDs and
       door-protection state before the destination can own those IDs

  2. Correctness-first intercell PVS quarantine:
     - after a load door, a large destination topology that initially proves
       only ONE active sector does NOT arm structural PVS
     - ordinary ray VISGRID remains active
     - PVS automatically releases as soon as normal evidence justifies >=2
       destination sectors
     - no guessed global fog/depth floor and no V22.2 arrival bubble

  3. Deep transition diagnostics:
     - records cell changes even during the existing 6s load-safe hold
     - source/destination, camera/topology XYZ, entry sector, bbox, neighbors,
       portals, nearest real doors/reverse link, shadow PVS IDs, engine stats

The previous V22.2 handoff experiment is NOT retained.
Only visgrid.lua is modified.
No OpenMW-running process gate is used.
Game binary, global topology, real-door graph and canonical navmesh DB are
protected by before/after snapshots and automatic sensor rollback on failure.
==================================================================
BANNER

echo
echo "===== 1/8 FETCH LIVE SENSOR + SNAPSHOT PROTECTED STATE ====="
scp -q "${SSH[@]}" "$DEV:$LUA" "$OUT/live-before.lua"
LIVE_SHA="$(sha256sum "$OUT/live-before.lua" | awk '{print $1}')"

readarray -t SNAP_BEFORE < <(ssh "${SSH[@]}" "$DEV" "
set -e
printf 'GAME=%s\\n' \"\$(sha256sum '$BIN' | awk '{print \$1}')\"
printf 'TOPO=%s\\n' \"\$(sha256sum '$TOPO' | awk '{print \$1}')\"
printf 'DOOR=%s\\n' \"\$(sha256sum '$DOOR' | awk '{print \$1}')\"
printf 'DB=%s\\n' \"\$(stat -c '%s %Y' '$DB')\"
printf 'TOPOCOUNT=%s\\n' \"\$(find '$TOPO_CELLS' -type f -name '*.lua' | wc -l)\"
printf 'DOORCOUNT=%s\\n' \"\$(find '$DOOR_CELLS' -type f -name '*.lua' | wc -l)\"
")
for line in "${SNAP_BEFORE[@]}"; do
    case "$line" in
        GAME=*) GAME_BEFORE="${line#GAME=}" ;;
        TOPO=*) TOPO_BEFORE="${line#TOPO=}" ;;
        DOOR=*) DOOR_BEFORE="${line#DOOR=}" ;;
        DB=*) DB_BEFORE="${line#DB=}" ;;
        TOPOCOUNT=*) TOPOCOUNT_BEFORE="${line#TOPOCOUNT=}" ;;
        DOORCOUNT=*) DOORCOUNT_BEFORE="${line#DOORCOUNT=}" ;;
    esac
done

echo "live sensor:   $LIVE_SHA"
echo "game SHA:      $GAME_BEFORE"
echo "topology SHA:  $TOPO_BEFORE"
echo "doorgraph SHA: $DOOR_BEFORE"
echo "DB size/mtime: $DB_BEFORE"
echo "topology shards: $TOPOCOUNT_BEFORE"
echo "doorgraph shards: $DOORCOUNT_BEFORE"

case "$LIVE_SHA" in
    "$NEW_SHA")
        BASELINE_MODE="already-v22.1d"
        echo "PASS: V22.1D is already installed."
        ;;
    "$V22_2_SHA")
        BASELINE_MODE="rollback-v22.2"
        echo "PASS: exact V22.2 regression build recognized."
        echo "      It will be replaced by a build derived from exact V22.1."
        ;;
    "$V22_1_SHA")
        BASELINE_MODE="v22.1"
        echo "PASS: exact V22.1 baseline already live."
        ;;
    *)
        echo "ERROR: live sensor is not an exact supported lineage."
        echo "Supported live SHAs:"
        echo "  V22.1  $V22_1_SHA"
        echo "  V22.2  $V22_2_SHA"
        echo "  V22.1D $NEW_SHA"
        echo "Nothing changed."
        exit 20
        ;;
esac

[ "$TOPOCOUNT_BEFORE" -eq 1321 ] || {
    echo "ERROR: global topology shard count is not the protected 1321 baseline."
    echo "Nothing changed."
    exit 21
}

