if [ -f "$HOME/Downloads/visgrid-tools/device.env" ]; then
    . "$HOME/Downloads/visgrid-tools/device.env" || true
fi
if [ -n "${TSP_DEV:-}" ]; then DEV="$TSP_DEV"
elif [ -n "${TSP_IP:-}" ]; then DEV="root@$TSP_IP"
else DEV="root@192.168.1.25"; fi
SSH=(-o BatchMode=yes -o ConnectTimeout=8)

V22_1_SHA="6dabab5641894968b51c2a8399ac206926662d4182d8445bb710ef7a0e2a7c45"
V22_2_SHA="4556f20dc78620843f624c91ca91be74254d75d423a007fac0ba1d0bc12e1c25"
PATCH_SHA="629fa6e708a9027f23598a5f96e618e88c16f4130d88da9e7d561879d94b7999"
