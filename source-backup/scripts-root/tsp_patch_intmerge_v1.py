P_ENGINE.append("        if (sTspIntMergeMode != 1 || sTspIntMergeCells.empty())")
P_ENGINE.append("            return;")
P_ENGINE.append("        for (std::map<const MWWorld::CellStore*, TspIntMergeCellState>::iterator it = sTspIntMergeCells.begin();")
