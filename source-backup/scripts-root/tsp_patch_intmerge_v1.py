P_ENGINE.append("        {")
P_ENGINE.append("            std::vector<ESM::RefNum> gone;")
P_ENGINE.append("            for (const TspIntMergeEntry& entry : it->second.mEntries)")
P_ENGINE.append("                if (entry.mLive->isDeleted() || !entry.mLive->mData.isEnabled())")
P_ENGINE.append("                    gone.push_back(entry.mRefNum);")
P_ENGINE.append("            if (gone.empty())")
P_ENGINE.append("                continue;")
P_ENGINE.append("            Log(Debug::Warning) << \"TSP_INTMERGE_V1 revalidate: \" << gone.size()")
P_ENGINE.append("                                << \" merged static(s) were disabled or deleted by a script - rebuilding the chunk\";")
P_ENGINE.append("            for (ESM::RefNum g : gone)")
P_ENGINE.append("                it->second.mExcluded.insert(g);")
P_ENGINE.append("            tspIntMergeRebuild(it->first, it->second);")
P_ENGINE.append("            outUnpaged.insert(outUnpaged.end(), gone.begin(), gone.end());")
P_ENGINE.append("        }")
P_ENGINE.append("    }")
