P_ENGINE.append("                                    << sTspIntMergeMin << \"), skipAnim=\" << skipAnim << \" skipMarker=\" << skipMarker;")
P_ENGINE.append("                outEntries.clear();")
P_ENGINE.append("                return nullptr;")
P_ENGINE.append("            }")
P_ENGINE.append("            osg::ref_ptr<osg::Group> chunk = new osg::Group;")
P_ENGINE.append("            chunk->setName(\"TSP_INTMERGE_CHUNK\");")
