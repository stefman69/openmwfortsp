P_ENGINE.append("       Interior static geometry merging. Interiors get none of the merging that")
P_ENGINE.append("       exterior active-grid ObjectPaging provides (renderingmanager gates paging on")
P_ENGINE.append("       isExterior), so a Caldera-class interior submits ~960 drawables a frame at a")
P_ENGINE.append("       measured ~100 us of CPU each (cull + State::apply + gl4es display-list replay")
P_ENGINE.append("       + light-list churn + driver copies). This builds ONE merged chunk per interior")
P_ENGINE.append("       cell at load, bucketed into room-sized groups so per-area point lighting")
P_ENGINE.append("       survives, and routes the merged refnums through the same mPagedRefs")
P_ENGINE.append("       suppression that exterior active-grid paging already uses in scene.cpp's")
P_ENGINE.append("       addObject. Merged geometry leaves the display-list path entirely (the")
P_ENGINE.append("       optimizer switches it to VBOs).")
P_ENGINE.append("       Correctness model, mirroring active-grid paging:")
P_ENGINE.append("       - only ESM::REC_STAT refs with a content-file refnum are merged; doors,")
P_ENGINE.append("         activators, containers, lights, actors all stay individual.")
P_ENGINE.append("       - templates needing update traversal (animated, NightDay, Herbalism, collada")
P_ENGINE.append("         anims) stay individual - same filter as paging's active grid.")
P_ENGINE.append("       - RefnumMarkers are attached like paging does, so refnum-based lookups on the")
P_ENGINE.append("         merged geometry keep working.")
P_ENGINE.append("       - a moved/deleted ref individuates through Scene::removeFromPagedRefs, which")
P_ENGINE.append("         calls tspIntMergeExcludeRef -> the chunk rebuilds without it.")
P_ENGINE.append("       - scripts that disable/delete a merged static are caught by")
P_ENGINE.append("         tspIntMergeRevalidate (called once per frame from Scene::update): the chunk")
P_ENGINE.append("         rebuilds without them and their refnums leave mPagedRefs, so a later enable")
P_ENGINE.append("         inserts them individually through the normal path.")
P_ENGINE.append("       - the chunk is attached under the cell's \"Cell Root\" on the first")
P_ENGINE.append("         Objects::insertBegin for that cell (every interior has at least a door, so")
P_ENGINE.append("         this always fires), and dies with the cell root on unload.")
P_ENGINE.append("       Env (read once): TSP_INTMERGE=1 arms it (default OFF - one launch A/B),")
