#!/bin/sh
# ===========================================================================
# apply_openmw_tsp_manager_v32_stock_os.sh   -   TSP_MGR_V32
#
# Makes the OpenMW Manager run on stock TrimUI OS as well as on CrossMix.
# Three device files, no binary rebuild - the two things that were killing it
# on the stock card both live in shell:
#
#   1. PORTS/OpenMW_Manager.sh          forced SDL_VIDEODRIVER=kmsdrm, and the
#                                       stock card's SDL2 has no KMSDRM
#                                       backend, so the UI died in SDL_Init
#                                       before drawing anything. Now it tries
#                                       kmsdrm first and falls through to a
#                                       driver this card actually has.
#   2. launcher/openmw-manager-action-v2.sh
#                                       ran the python backend through its
#                                       `#!/usr/bin/env python3` shebang, and
#                                       python3 is not on PATH on stock OS.
#                                       Now it resolves the interpreter.
#   3. tools/OpenMW_Generate_Full_Navmesh_3Worker.sh
#                                       had a bash array, process substitution,
#                                       printf %q, an ERR trap and a re-exec
#                                       into /bin/bash that loops forever when
#                                       /bin/bash is a busybox symlink. Ported
#                                       to POSIX; the bash path is unchanged.
#
# MODES
#   selftest       host-side only: decode, checksum and parse every artifact
#   install        the default: back up, gate, install, verify, roll back on
#                  any failure. Nothing is written unless all three files pass
#                  the card's own `sh -n`.
#   verify         read-only: what is installed and what first launch still
#                  needs
#   collect        pull the manager and game logs into ~/Downloads
#   rollback       restore the most recent backup this script made
#
# POINTING IT AT A CARD - first match wins:
#   TSP=root@192.168.1.21 sh apply_openmw_tsp_manager_v32_stock_os.sh install
#   $TSP_DEV / ~/.tsp_dev / root@192.168.1.12
# ===========================================================================

MODE="${1:-install}"

if ! grep -q '^# TSP_MGR_V32 END OF FILE$' "$0" 2>/dev/null; then
    echo "v32: this copy of the script is truncated - download it again" >&2
    exit 1
fi

# --- device resolution (CONSTRAINT-two-cards-are-addressed-by-name) --------
DEVICE=""
[ -n "${TSP:-}" ] && DEVICE="$TSP"
[ -z "$DEVICE" ] && [ -n "${DEV:-}" ] && DEVICE="$DEV"
[ -z "$DEVICE" ] && [ -n "${TSP_DEV:-}" ] && DEVICE="$TSP_DEV"
[ -z "$DEVICE" ] && [ -f "$HOME/.tsp_dev" ] && DEVICE="$(cat "$HOME/.tsp_dev" 2>/dev/null)"
[ -z "$DEVICE" ] && DEVICE="root@192.168.1.12"
true

HOSTPART="${DEVICE#*@}"
LABEL=""
if [ -f "$HOME/.tsp_hosts" ]; then
    LABEL="$(awk -v d="$DEVICE" '$2 == d { print $1; exit }' "$HOME/.tsp_hosts" 2>/dev/null)"
fi
[ -n "$LABEL" ] || LABEL="$(echo "$HOSTPART" | tr '.' '-')"

DL="$HOME/Downloads"
[ -d "$DL" ] || DL="$HOME"
TS="$(date +%Y%m%d-%H%M%S)"
SSHOPTS="-o ConnectTimeout=10 -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR"

ROOT="/mnt/SDCARD/data/ports/openmw"
BACKUPS="/mnt/SDCARD/data/ports/Backups"
STAGE="/tmp/tsp-v32-stage"

# name | device path | md5 of the ORIGINAL this was patched from | md5 of the PATCHED file
