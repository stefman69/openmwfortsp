    name="$(field "$row" 1)"
    dpath="$(field "$row" 2)"
    orig="$(field "$row" 3)"
    have="$(echo "$DEVSUM" | awk -v p="$dpath" '$2 == p { print $1 }')"
    if [ -z "$have" ]; then
        echo "      MISSING on the card: $dpath"
        MISMATCH=1
    elif [ "$have" = "$orig" ]; then
        echo "      ok   $name matches the source this patch was built from"
    elif [ "$have" = "$(field "$row" 4)" ]; then
        echo "      note $name is ALREADY at V3.2 - it will be rewritten identically"
    else
        echo "      DIFFERENT: $name on the card is $have, this patch was built from $orig"
