    echo "         TSP=$DEVICE sh ~/Downloads/tsp_mgr.sh pull"
    echo "      and send them over, or re-run with FORCE=1 if you are sure."
    [ "${FORCE:-0}" = "1" ] || die "refusing to overwrite a file this patch does not know"
    echo "      FORCE=1 set - continuing anyway"
fi

step 4/6 "backing up, then installing behind the card's own parser"
for row in $FILES; do
    name="$(field "$row" 1)"
    scp $SSHOPTS "$WORK/$name" "$DEVICE:$STAGE/$name" >/dev/null 2>&1 || {
        ssh -n $SSHOPTS "$DEVICE" "mkdir -p '$STAGE'" >/dev/null 2>&1
        scp $SSHOPTS "$WORK/$name" "$DEVICE:$STAGE/$name" >/dev/null 2>&1 || die "scp of $name failed"
    }
    echo "      staged $name"
done

PATCHED_W="$(field "$(echo "$FILES" | grep '^OpenMW_Manager.sh|')" 4)"
PATCHED_A="$(field "$(echo "$FILES" | grep '^openmw-manager-action-v2.sh|')" 4)"
PATCHED_G="$(field "$(echo "$FILES" | grep '^OpenMW_Generate_Full|')" 4)"
ssh $SSHOPTS "$DEVICE" "BACKUPS='$BACKUPS' ROOT='$ROOT' STAGE='$STAGE' TS='$TS' PATCHED_W='$PATCHED_W' PATCHED_A='$PATCHED_A' PATCHED_G='$PATCHED_G' sh -s" <<'V32_INSTALL_EOF'
set -u
# ONE canonical pre-V3.2 backup, never overwritten. Running install twice used
# to make a second backup containing this tool's OWN output, and rollback then
# restored the patch instead of undoing it - the exact trap in the tool index.
BDIR="$BACKUPS/v32-pre"
mkdir -p "$BDIR" || { echo "FATAL cannot create $BDIR"; exit 1; }

W=/mnt/SDCARD/Roms/PORTS/OpenMW_Manager.sh
A="$ROOT/launcher/openmw-manager-action-v2.sh"
G="$ROOT/tools/OpenMW_Generate_Full_Navmesh_3Worker.sh"

pair() {
    case "$1" in
        OpenMW_Manager.sh) echo "$W" ;;
        openmw-manager-action-v2.sh) echo "$A" ;;
        OpenMW_Generate_Full_Navmesh_3Worker.sh) echo "$G" ;;
    esac
}

NAMES="OpenMW_Manager.sh openmw-manager-action-v2.sh OpenMW_Generate_Full_Navmesh_3Worker.sh"

patched_md5() {
    case "$1" in
        OpenMW_Manager.sh) echo "$PATCHED_W" ;;
        openmw-manager-action-v2.sh) echo "$PATCHED_A" ;;
        OpenMW_Generate_Full_Navmesh_3Worker.sh) echo "$PATCHED_G" ;;
    esac
}

# 1. verified backups - a backup that does not read back is not a backup, and
#    a file this tool already wrote is never backed up over the original.
for n in $NAMES; do
    t="$(pair "$n")"
    [ -f "$t" ] || { echo "FATAL missing on device: $t"; exit 1; }
    cur=$(md5sum "$t" | cut -d' ' -f1)
    if [ -f "$BDIR/$n" ]; then
        echo "  backup kept   $n ($(md5sum "$BDIR/$n" | cut -c1-8)) - not overwritten"
        continue
    fi
    if [ "$cur" = "$(patched_md5 "$n")" ]; then
        echo "FATAL $n is already at V3.2 but $BDIR holds no pre-V3.2 copy of it."
        echo "      Restoring it first is the only way rollback can mean anything."
        echo "      Look in $BACKUPS, or re-pull the file, then run install again."
        exit 1
    fi
    cp -f "$t" "$BDIR/$n" || { echo "FATAL backup failed: $n"; exit 1; }
    b=$(md5sum "$BDIR/$n" | cut -d' ' -f1)
    [ "$cur" = "$b" ] || { echo "FATAL backup of $n does not match the original"; exit 1; }
    echo "  backed up $n -> $BDIR/$n ($cur)"
done
