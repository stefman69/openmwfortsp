    out=$(/bin/sh -n "$s" 2>&1)
    if [ -n "$out" ]; then
        echo "FATAL this card's /bin/sh cannot parse the new $n:"
        echo "$out" | sed 's/^/    /'
        echo "NOTHING WAS CHANGED."
        exit 1
    fi
    echo "  parse ok  $n"
done

# 3. commit
for n in $NAMES; do
    t="$(pair "$n")"
    cp -f "$STAGE/$n" "$t" || { echo "FATAL install failed: $n"; exit 1; }
    chmod 755 "$t" 2>/dev/null
done

# 4. verify what landed; restore everything if any of it is wrong
BAD=0
for n in $NAMES; do
    t="$(pair "$n")"
    a=$(md5sum "$STAGE/$n" | cut -d' ' -f1)
    b=$(md5sum "$t" | cut -d' ' -f1)
    if [ "$a" != "$b" ]; then echo "  BAD $n did not land intact"; BAD=1; continue; fi
    out=$(/bin/sh -n "$t" 2>&1)
    if [ -n "$out" ]; then echo "  BAD $n does not parse once installed"; BAD=1; continue; fi
    if [ ! -x "$t" ]; then echo "  BAD $n is not executable"; BAD=1; continue; fi
    echo "  installed $n  $b"
done
if [ "$BAD" -ne 0 ]; then
    echo "ROLLING BACK"
    for n in $NAMES; do cp -f "$BDIR/$n" "$(pair "$n")" && chmod 755 "$(pair "$n")"; done
    echo "ROLLED BACK to $BDIR"
    exit 1
fi

