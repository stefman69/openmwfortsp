# ---------------------------------------------------------------------------
# HOST SELFTEST - always runs, whatever the mode
# ---------------------------------------------------------------------------
step 1/6 "host selftest: decoding and checking the three artifacts"
emit "$WORK" || die "could not decode the embedded artifacts"

HOSTFAIL=0
for row in $FILES; do
    name="$(field "$row" 1)"
    want="$(field "$row" 4)"
    got="$(md5host "$WORK/$name")"
    if [ "$got" != "$want" ] && [ "$got" != "NOMD5" ]; then
        echo "      BAD  $name decoded to $got, expected $want"
        HOSTFAIL=1
    else
        echo "      ok   $name  $got  $(wc -l < "$WORK/$name" | tr -d ' ') lines"
    fi
done
[ "$HOSTFAIL" -eq 0 ] || die "an embedded artifact did not decode correctly"

# Parse under every shell this machine has. bash is required; busybox ash and
# dash are checked when present, because the two cards run different shells.
for sh_try in bash dash "busybox ash"; do
    case "$sh_try" in
        "busybox ash") command -v busybox >/dev/null 2>&1 || continue ;;
        *)             command -v "$sh_try" >/dev/null 2>&1 || continue ;;
    esac
    for row in $FILES; do
        name="$(field "$row" 1)"
        if ! $sh_try -n "$WORK/$name" 2>"$WORK/parse.err"; then
            echo "      PARSE FAIL  $name under $sh_try:"
            sed 's/^/        /' "$WORK/parse.err"
            HOSTFAIL=1
        fi
    done
    [ "$HOSTFAIL" -eq 0 ] && echo "      parses clean under $sh_try"
done
[ "$HOSTFAIL" -eq 0 ] || die "a patched file does not parse"

# The action backend carries its own selftest.
if command -v bash >/dev/null 2>&1; then
    if bash "$WORK/openmw-manager-action-v2.sh" selftest 2>&1 | grep -q 'SELFTEST_PASS'; then
        echo "      action backend selftest PASS"
    else
        die "the action backend selftest did not pass on this machine"
    fi
fi

if [ "$MODE" = "selftest" ]; then
    echo
    echo "HOST SELFTEST PASSED. Nothing was sent to any device."
    echo "To install:  TSP=$DEVICE sh $0 install"
    cleanup
    exit 0
fi

