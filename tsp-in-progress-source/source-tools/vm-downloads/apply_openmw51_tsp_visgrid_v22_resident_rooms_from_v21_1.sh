EXPECTED_V22_SHA="eb8331500d9ce7b638e79729a21477af5dffb9fb4c9bf7923c60a855452b3533"
EXPECTED_PATCH_SHA="22302c02b68be5f80f79269c1df844a4b5250005109ecb05e62425b767afc485"

STAMP="$(date +%Y%m%d-%H%M%S)"
OUT="$HOME/Downloads/openmw51-visgrid-v22-resident-$STAMP"
LOG="$OUT/controller.log"
mkdir -p "$OUT"
exec > >(tee "$LOG") 2>&1

fail() {
    rc=$?
    line="${1:-?}"
    cmd="${2:-?}"
    trap - ERR
    echo
    echo "=================================================================="
    echo "V22 RESIDENT-SECTOR INSTALLER STOPPED"
    echo "=================================================================="
    echo "exit=$rc line=$line"
    echo "command: $cmd"
    echo "No automatic rerun was attempted."
    echo "Log: $LOG"
    exit "$rc"
}
trap 'fail "$LINENO" "$BASH_COMMAND"' ERR

cat <<'BANNER'
==================================================================
OPENMW 0.51 — VISGRID V22 RESIDENT ROOM-GROUP WORKING SET
==================================================================
Core policy:
  - current topology room stays structural
  - up to 3 non-current room-groups stay resident normally
  - positive rays PROMOTE rooms; negative rays never evict them
  - every promotion gets a hard 5-second minimum
  - after 5s, a resident room is replaced only when another room needs its slot
  - portal/view + movement direction prefetch likely next rooms
  - ray-promoted sectors keep only the angular portion actually proved visible
  - if the player itself is topology-unmapped, rays may still discover/pin sectors
  - old V21 ray hold remains as a 5-second fallback where sector mapping fails

This modifies visgrid.lua only.
Game binary, real-door graph, global topology shards and navmesh DB are protected
by before/after snapshots, not brittle hard-coded hashes.
No OpenMW-running process gate is used.
==================================================================
BANNER


echo
echo "===== 1/7 FETCH EXACT LIVE SENSOR + SNAPSHOT PROTECTED STATE ====="
ssh "${SSH[@]}" "$DEV" "test -s '$LUA'; test -s '$BIN'; test -s '$TOPO'; test -s '$DOOR'; test -s '$DB'"
scp -q "${SSH[@]}" "$DEV:$LUA" "$OUT/visgrid-v21-live.lua"

LIVE_SHA="$(sha256sum "$OUT/visgrid-v21-live.lua" | awk '{print $1}')"
GAME_BEFORE="$(ssh "${SSH[@]}" "$DEV" "sha256sum '$BIN'" | awk '{print $1}')"
TOPO_BEFORE="$(ssh "${SSH[@]}" "$DEV" "sha256sum '$TOPO'" | awk '{print $1}')"
DOOR_BEFORE="$(ssh "${SSH[@]}" "$DEV" "sha256sum '$DOOR'" | awk '{print $1}')"
DB_BEFORE="$(ssh "${SSH[@]}" "$DEV" "stat -c '%s %Y' '$DB'")"

printf 'sensor SHA:   %s
' "$LIVE_SHA"
printf 'game SHA:     %s
' "$GAME_BEFORE"
printf 'topology SHA: %s
' "$TOPO_BEFORE"
printf 'doorgraph SHA:%s
' "$DOOR_BEFORE"
printf 'DB size/mtime:%s
' "$DB_BEFORE"

if [ "$LIVE_SHA" = "$EXPECTED_V22_SHA" ]; then
    echo "PASS: exact V22 is already installed."
    exit 0
fi

[ "$LIVE_SHA" = "$EXPECTED_BASE_SHA" ] || {
    echo "ERROR: V22 is intentionally based only on the exact tested V21.1."
    echo "Expected V21.1: $EXPECTED_BASE_SHA"
    echo "Live:         $LIVE_SHA"
    echo "Nothing changed."
    exit 20
