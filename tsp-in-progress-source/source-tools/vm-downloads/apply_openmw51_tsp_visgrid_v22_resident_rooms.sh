grep -Fq 'TSP_VISGRID_LUA_V21_DOORGRAPH_VIEWHOLD' "$OUT/visgrid-v21-live.lua"
grep -Fq 'TSP_VISGRID_REAL_DOOR_GRAPH_V1' <(ssh "${SSH[@]}" "$DEV" "cat '$DOOR'")

echo "PASS: exact V21 baseline + installed real-door sidecar present."


