EXPECTED_V22_SHA="3bbed5a2c763cf76a634afd2ea305b2a1c01a1941958e7afcbdb2458914e4a1a"
EXPECTED_PATCH_SHA="c4d4642c1bca9133420259ac7bf9ef94990131beb36d2dccd22ff2c3be110bec"

STAMP="$(date +%Y%m%d-%H%M%S)"
OUT="$HOME/Downloads/openmw51-visgrid-v22-resident-$STAMP"
LOG="$OUT/controller.log"
mkdir -p "$OUT"
exec > >(tee "$LOG") 2>&1

fail() {
    rc=$?
    line="${1:-?}"
    cmd="${2:-?}"
    trap - ERR
    echo
    echo "=================================================================="
    echo "V22 RESIDENT-SECTOR INSTALLER STOPPED"
    echo "=================================================================="
    echo "exit=$rc line=$line"
    echo "command: $cmd"
    echo "No automatic rerun was attempted."
    echo "Log: $LOG"
    exit "$rc"
}
trap 'fail "$LINENO" "$BASH_COMMAND"' ERR

