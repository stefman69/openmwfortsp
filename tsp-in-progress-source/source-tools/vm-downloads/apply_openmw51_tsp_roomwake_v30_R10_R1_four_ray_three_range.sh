#!/usr/bin/env python3
import sys

MARK = 'TSP_ROOM_ADAPTIVE_RANGE_051_V30_R10'


def read(path):
    with open(path, 'r', encoding='utf-8', newline='') as f:
        return f.read()


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def replace_one(text, old, new, label):
    count = text.count(old)
    if count != 1:
        raise RuntimeError('%s count=%d expected 1 token=%r' % (label, count, old))
    return text.replace(old, new, 1)


def line_start(text, pos):
    return text.rfind('\n', 0, pos) + 1


def line_end(text, pos):
    end = text.find('\n', pos)
    return len(text) if end < 0 else end + 1


def indent_at(text, pos):
    start = line_start(text, pos)
    end = line_end(text, pos)
    line = text[start:end]
    return line[:len(line) - len(line.lstrip(' \t'))]


def patch_scene(sc):
    for token in (
        'TSP_ROOM_RENDER_SAFETY_051_V30_R9',
        'tspRoomLightNearXY = 2800.f',
        'tspRoomLightNearZ = 384.f',
        'tspNearWakeXY = 1100.f',
        'tspNearWakeZ = 320.f',
        'tspNearHoldXY = 1450.f',
        'tspNearHoldZ = 384.f',
    ):
        if token not in sc:
            raise RuntimeError('R9 scene precondition missing: ' + token)
    if MARK in sc:
        raise RuntimeError('R10 scene marker already present')

    old = 'constexpr float tspRoomLightNearXY = 2800.f;'
    pos = sc.index(old)
