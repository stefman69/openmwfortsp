mapState.r10Classify = function(distances)
    if distances == nil then
        -- An API/direction failure is not geometric evidence. Fail fully open.
        mapState.r10TightSupport = 0
        mapState.r10SmallSupport = 0
        mapState.r10LongBurst = 2
        mapState.r10SpaceScore = 2.0
        mapState.r10SetRangeMode(0, 'ray-api-failure', nil)
        return
    end

    local ordered = { distances[1], distances[2], distances[3] }
    table.sort(ordered)
    local forwardMax = ordered[3]
    local weighted = ordered[1] * 0.10 + ordered[2] * 0.25 + ordered[3] * 0.65
    local up = distances[4]
    local allSmall = forwardMax <= mapState.r10VeryEnter
    local allTight = forwardMax <= mapState.r10TightEnter
    mapState.r10WeightedDepth = weighted
    mapState.r10SampleCount = mapState.r10SampleCount + 1

    if allSmall and up <= mapState.r10UpVeto then
        mapState.r10SmallSupport = math.min(mapState.r10VerySamples,
            mapState.r10SmallSupport + 1)
        mapState.r10TightSupport = math.min(mapState.r10VerySamples,
            mapState.r10TightSupport + 1)
    elseif allTight then
        mapState.r10SmallSupport = math.max(0, mapState.r10SmallSupport - 2)
        mapState.r10TightSupport = math.min(mapState.r10VerySamples,
            mapState.r10TightSupport + 1)
    else
        mapState.r10SmallSupport = math.max(0, mapState.r10SmallSupport - 10)
        mapState.r10TightSupport = math.max(0, mapState.r10TightSupport - 3)
    end

    if forwardMax > mapState.r10TightExit then
        mapState.r10LongBurst = math.min(3, mapState.r10LongBurst + 1)
    else
        mapState.r10LongBurst = math.max(0, mapState.r10LongBurst - 1)
    end

    local prior, kind, span = mapState.r10TopologyPrior()
    mapState.r10TopoPrior = prior
    mapState.r10TopoKind = kind
    mapState.r10TopoSpan = span

    local target = mapState.r10DepthTarget(weighted)
    if up > mapState.r10UpVeto then
        local upTarget = 1.25 + math.min(0.75,
            (up - mapState.r10UpVeto) / 900.0 * 0.75)
        target = math.max(target, upTarget)
    end

    -- Asymmetric decaying evidence: upward/open reports move roughly 10x as
    -- fast as sustained shrink reports. Both updates are delta-to-target, so
    -- the influence of repeated identical reports tapers instead of growing
    -- without bound. A 1% live topology pull remains overridable by long-term
    -- ray agreement.
    local alpha = 0.055
    if target > mapState.r10SpaceScore then
        alpha = forwardMax >= 1800.0 and 0.58 or 0.38
    end
    mapState.r10SpaceScore = mapState.r10SpaceScore
        + (target - mapState.r10SpaceScore) * alpha
    mapState.r10SpaceScore = mapState.r10SpaceScore
        + (prior - mapState.r10SpaceScore) * 0.01
    mapState.r10SpaceScore = mapState.r10Clamp(mapState.r10SpaceScore, 0.0, 2.0)

    local current = mapState.r10RangeMode
    local desired = current
    local reason = 'hold'

    -- One contradictory opening immediately removes VERY_TIGHT. A second
    -- continuing long report advances TIGHT to OPEN. This preserves the
    -- requested medium step while making doorway/open-room recovery fast.
    if current == 2 and (forwardMax > mapState.r10VeryExit or up > mapState.r10UpVeto) then
        desired = 1
        reason = 'first-opening-witness'
    elseif forwardMax > mapState.r10TightExit and mapState.r10LongBurst >= 2 then
        desired = 0
        reason = 'two-long-witnesses'
    elseif current == 1 and mapState.r10SpaceScore >= 1.50
        and forwardMax <= mapState.r10TightExit then
        desired = 0
        reason = 'authority-open'
    elseif allSmall and up <= mapState.r10UpVeto
        and mapState.r10SmallSupport >= mapState.r10VerySamples
        and mapState.r10SpaceScore <= 0.68 then
        desired = 2
        reason = 'sustained-all-three-small'
    elseif current == 0 and allTight
        and mapState.r10TightSupport >= mapState.r10TightSamples
        and mapState.r10SpaceScore <= 1.20 then
        desired = 1
        reason = 'weighted-tight-authority'
    end

    mapState.r10SetRangeMode(desired, reason, distances)
end

mapState.r10RayUpdate = function(dt)
    local cell = self.cell
    if cell == nil or cell.isExterior then
        mapState.r10LastCell = cell
        mapState.r10LastTopoCell = nil
        mapState.r10TightSupport = 0
        mapState.r10SmallSupport = 0
        mapState.r10LongBurst = 0
        mapState.r10SpaceScore = 2.0
        mapState.r10SetRangeMode(0, 'not-interior', nil)
        return
    end

    if mapState.r10LastCell ~= cell or mapState.r10LastTopoCell ~= mapState.topoCell then
        local reason = mapState.r10LastCell ~= cell and 'cell-change' or 'topology-change'
        mapState.r10LastCell = cell
        mapState.r10LastTopoCell = mapState.topoCell
        mapState.r10ResetAuthority(reason)
    end

    mapState.r10RayElapsed = mapState.r10RayElapsed + math.max(0.0, tonumber(dt or 0) or 0)
    if mapState.r10RayElapsed < mapState.r10RayPeriod then return end
    mapState.r10RayElapsed = 0.0
    local distances = mapState.r10SampleFour()
    mapState.r10Classify(distances)
    mapState.r10ReportElapsed = mapState.r10ReportElapsed + mapState.r10RayPeriod
    if mapState.r10ReportElapsed >= mapState.r10ReportPeriod then
        mapState.r10ReportElapsed = 0.0
        mapState.r10AuthorityReport(distances)
    end
end

mapState.r10OnFrame = function(dt)
    mapState.r10BaseOnFrame(dt)
    mapState.r10RayUpdate(dt)
end

